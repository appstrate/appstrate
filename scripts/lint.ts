/// <reference types="bun" />

/**
 * The repo's ESLint entrypoint — `bun run lint` (and `lint:fix`).
 *
 * It exists for one reason: to scope ESLint to TRACKED content instead of the
 * working tree.
 *
 * ─── Why not `eslint .` ──────────────────────────────────────────────
 *
 * `eslint .` walks the filesystem, so its scope is "every file on this
 * developer's disk that the config matches, minus `.eslintignore`-style
 * `ignores`". Since `eslint.config.mjs` was widened from a six-glob directory
 * roster to `**\/*.{ts,tsx}` — a real fix, five tracked files had been covered
 * by nothing — that scope includes any untracked, non-gitignored `.ts`
 * anywhere in the tree. Measured on this branch: an untracked
 * `zz-probe/p.ts` containing `export const a: any = 1;` failed `bun run lint`,
 * which fails `bun run check`, which fails `.husky/pre-push`. A scratch file
 * nobody intends to commit could block a push.
 *
 * The repo already answered this question twice, in the two sibling gates, and
 * both wrote the principle down: `scripts/lint-manifest-casing.ts` and
 * `scripts/verify-compose-defaults.ts` drive their scans from `git ls-files`
 * because "an untracked scratch file on somebody's machine is not this gate's
 * business". This is the same move for the same reason — and it keeps the
 * widening's actual benefit, since a tracked file is covered the day it is
 * committed regardless of which directory it lands in.
 *
 * ─── Why a script and not a shell one-liner in package.json ──────────
 *
 * `eslint $(git ls-files …)` bets on the shell's word-splitting; `bun run`
 * executes scripts through its own shell, which is not the interactive one and
 * not a POSIX sh either. And `git ls-files | xargs eslint` is worse: xargs may
 * split the list into SEVERAL eslint invocations, which breaks both `--cache`
 * (each run rewrites `.eslintcache` from its own subset) and the exit code
 * (only the last invocation's survives without extra plumbing).
 *
 * Neither is needed. Measured 2026-08-25: 2201 tracked
 * `.ts/.tsx/.js/.jsx/.mjs/.cjs` files, 101 795 bytes of argv, against this
 * machine's `getconf ARG_MAX` of 1 048 576 — a single invocation fits with an
 * order of magnitude to spare, so the file list is passed in one `spawn`.
 *
 * Any extra argument is forwarded to eslint verbatim, which is what makes
 * `lint:fix` (`--fix`) the same scope as `lint` rather than a second
 * definition of it.
 *
 * `//#lint`'s turbo `inputs` mirror this scope — see the note there.
 */

import { existsSync } from "node:fs";
import { join } from "node:path";

const REPO_ROOT = join(import.meta.dir, "..");

/**
 * The extensions eslint actually has an opinion about here: `.ts`/`.tsx` come
 * from `eslint.config.mjs`'s `ALL_TS`, and `.js`/`.jsx`/`.mjs`/`.cjs` are
 * ESLint's own defaults (`eslint.config.mjs` itself is one of them).
 */
const LINTABLE_GLOBS = ["*.ts", "*.tsx", "*.js", "*.jsx", "*.mjs", "*.cjs"];

/**
 * Every tracked lintable file, discovered — not enumerated.
 *
 * `git ls-files` lists what is in the INDEX, which can name a file already
 * removed from the working tree (a `git rm` not yet committed, a refactor in
 * flight). eslint hard-errors on a path that does not exist, so those are
 * filtered — the same allowance `lint-manifest-casing.ts` makes for `ENOENT`,
 * and for the same reason: a checkout mid-edit is not a lint finding.
 */
function trackedLintableFiles(): string[] {
  const result = Bun.spawnSync({
    cmd: ["git", "ls-files", "-z", "--", ...LINTABLE_GLOBS],
    cwd: REPO_ROOT,
    stdout: "pipe",
    stderr: "pipe",
  });
  if (result.exitCode !== 0) {
    throw new Error(
      `git ls-files failed (exit ${result.exitCode}): ${result.stderr.toString().trim()}`,
    );
  }
  const files = result.stdout
    .toString()
    .split("\0")
    .filter(Boolean)
    .filter((rel) => existsSync(join(REPO_ROOT, rel)))
    .sort();
  if (files.length === 0) {
    throw new Error("git ls-files matched no lintable file — the gate would pass vacuously.");
  }
  return files;
}

const files = trackedLintableFiles();

const eslint = join(REPO_ROOT, "node_modules/.bin/eslint");
if (!existsSync(eslint)) {
  throw new Error(`${eslint} not found — run \`bun install\`.`);
}

const proc = Bun.spawnSync({
  cmd: [
    eslint,
    "--cache",
    "--cache-strategy",
    "content",
    // Naming files explicitly turns "this file is in `ignores`" from a silent
    // skip into a warning, and `apps/web/src/api/schema.d.ts` (generated by
    // scripts/generate-api-types.ts) is both tracked and ignored. Measured
    // 2026-08-25: it is the only tracked file in that state, and without this
    // flag `bun run lint` printed one warning about it on every run.
    "--no-warn-ignored",
    ...Bun.argv.slice(2),
    ...files,
  ],
  cwd: REPO_ROOT,
  stdio: ["inherit", "inherit", "inherit"],
});

process.exit(proc.exitCode ?? 1);
