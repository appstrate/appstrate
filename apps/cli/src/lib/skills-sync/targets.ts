/**
 * Build `dest` under `stagingParent`, then move it into place.
 *
 * POSIX `rename` cannot overwrite a non-empty directory, so an existing
 * destination is first renamed aside and deleted afterwards. The window where
 * neither exists is one `rename` wide, and a crash inside it leaves the
 * destination absent rather than half-written — the failure mode the whole
 * dance is chosen for.
 *
 * `stagingParent` is a caller decision because the two target shapes disagree
 * about what is safe to leave lying around: it must be on the destination's
 * filesystem (`rename`), and out of any directory a skill runner enumerates.
 */
async function withStaging(
  dest: string,
  stagingParent: string,
  build: (staging: string) => Promise<void>,
): Promise<void> {
  await mkdir(dirname(dest), { recursive: true });
  await mkdir(stagingParent, { recursive: true });
  const suffix = `${process.pid}-${Date.now()}`;
  const staging = join(stagingParent, `build-${suffix}`);
  const retired = join(stagingParent, `retired-${suffix}`);
  try {
    await mkdir(staging, { recursive: true });
    await build(staging);
    let hadPrevious = true;
    try {
      await rename(dest, retired);
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
      hadPrevious = false;
    }
    try {
      await rename(staging, dest);
    } catch (err) {
      if (hadPrevious) await rename(retired, dest).catch(() => {});
      throw err;
    }
    if (hadPrevious) await rm(retired, { recursive: true, force: true });
  } finally {
    await rm(staging, { recursive: true, force: true }).catch(() => {});
    await rm(retired, { recursive: true, force: true }).catch(() => {});
    // Best effort: empty after a clean run, and `rmdir` on a non-empty one
    // (a concurrent sync still building) fails harmlessly.
    await rmdir(stagingParent).catch(() => {});
  }
}

/** Write a materialized tree under `dir`, creating intermediate directories. */
async function writeTreeInto(dir: string, files: Record<string, Uint8Array>): Promise<void> {
  await mkdir(dir, { recursive: true });
  for (const path of Object.keys(files).sort()) {
    const target = join(dir, path);
    await mkdir(dirname(target), { recursive: true });
    // `flag: "wx"` — the staging tree is fresh, so an existing target means
    // two entries normalized to the same path and one would silently win.
    await writeFile(target, files[path]!, { flag: "wx" });
  }
}
